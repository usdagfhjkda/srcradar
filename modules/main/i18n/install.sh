#!/usr/bin/env bash
# SPDX-License-Identifier: Apache-2.0
#
# modules/main/i18n/install.sh — install the i18n language module
#
# What the i18n module provides:
#   - two message tables at modules/main/i18n/locales/{zh,en}.json
#   - i18n.py (python-side t()) and i18n.sh (shell-side t())
#   - a config/lang.conf at the repository root declaring the language
#
# This module installs no binary, reaches no network and writes no DB.
# The message tables are plain data — they work as soon as they are
# checked out.
#
# Usage:
#   bash install.sh                # write config/lang.conf (never overwrites)
#   bash install.sh --check        # validate the message tables only
#   bash install.sh --lang en      # write config/lang.conf with that language
#
# Exit codes:
#   0  success
#   1  bad argument
#   2  message table missing or corrupt
#   3  write failed
#

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

# The runtime messages below go through t(), so the shell-side lookup has
# to be available before anything is printed.
# shellcheck source=./i18n.sh
source "${SCRIPT_DIR}/i18n.sh"

log()  { printf '[i18n] %s\n' "$*"; }
warn() { printf '[i18n][warn]  %s\n' "$*" >&2; }
err()  { printf '[i18n][err]  %s\n' "$*" >&2; }

usage() {
    sed -n "2,18p" "${SCRIPT_DIR}/$(basename "${BASH_SOURCE[0]}")"
}

# Repository root: walk up to the level holding modules/ and install.sh.
find_root() {
    local d
    d="$SCRIPT_DIR"
    while [ "$d" != "/" ]; do
        if [ -d "$d/modules" ] && [ -f "$d/install.sh" ]; then
            printf '%s' "$d"
            return 0
        fi
        d="$(dirname "$d")"
    done
    return 1
}

ROOT="$(find_root || true)"
if [ -z "$ROOT" ]; then
    err "$(t i18n.locale_root_missing)"
    exit 3
fi

LOCALES_DIR="$SCRIPT_DIR/locales"
CONF_DIR="$ROOT/config"
CONF_FILE="$CONF_DIR/lang.conf"

# ---- message table check ----
# Each table must be valid JSON and a flat {key: string} object.
check_locales() {
    local rc=0 lang f
    for lang in zh en; do
        f="$LOCALES_DIR/$lang.json"
        if [ ! -f "$f" ]; then
            err "$(t i18n.locale_table_missing file="$f")"
            rc=2
            continue
        fi
        if ! python3 -c '
import json, sys
with open(sys.argv[1], encoding="utf-8") as fh:
    data = json.load(fh)
if not isinstance(data, dict):
    raise SystemExit("not a JSON object")
bad = [k for k, v in data.items() if not isinstance(k, str) or not isinstance(v, str)]
if bad:
    raise SystemExit("non-string key/value: " + ", ".join(bad[:5]))
' "$f" 2>/dev/null; then
            err "$(t i18n.locale_table_broken file="$f")"
            rc=2
        else
            n="$(python3 -c 'import json,sys; print(len(json.load(open(sys.argv[1],encoding="utf-8"))))' "$f")"
            log "$(t i18n.locale_table_ok file="$lang.json" count="$n")"
        fi
    done
    return $rc
}

# ---- write config/lang.conf ----
# Same pattern as write_db_conf() in the top-level install.sh: an existing
# file is never overwritten (the operator's choice wins).
write_lang_conf() {
    local lang="$1"
    if [ -f "$CONF_FILE" ]; then
        log "$(t i18n.locale_exists)"
        return 0
    fi
    mkdir -p "$CONF_DIR"
    cat > "$CONF_FILE" <<EOF
# srcradar — UI language config (auto-generated by modules/main/i18n/install.sh)
#
# lang selects the language of user-visible output:
#   - command line --help and runtime messages
#   - the dashboard pages
#   - the daily report and the notification email body
#
# Resolution order (handled by modules/main/i18n/i18n.{py,sh}):
#   1) the SRCDAR_LANG environment variable
#   2) the lang field in this file
#   3) en as the default
#
# Accepted values: zh (Chinese) / en (English)
#
# This file lives under .gitignore and is not tracked; delete it and
# install.sh will regenerate it.
lang=$lang
EOF
    log "$(t i18n.locale_written lang="$lang")"
}

main() {
    local mode="install" lang="en"
    while [ $# -gt 0 ]; do
        case "$1" in
            --check) mode="check"; shift ;;
            --lang)
                [ $# -ge 2 ] || { err "$(t i18n.locale_lang_needs_arg)"; exit 1; }
                lang="$2"; shift 2 ;;
            --yes|"") shift ;;
            -h|--help) usage; exit 0 ;;
            *) err "unknown arg: $1"; usage; exit 1 ;;
        esac
    done

    case "$lang" in
        zh|en) ;;
        *) err "$(t i18n.locale_lang_unsupported lang="$lang")"; exit 1 ;;
    esac

    check_locales || exit 2

    if [ "$mode" = "check" ]; then
        log "$(t i18n.locale_check_done)"
        exit 0
    fi

    write_lang_conf "$lang" || exit 3
    exit 0
}

main "$@"
