PY
    rc=${PIPESTATUS[0]}
    BUSINESS_ID=$(tail -n1 /tmp/.bootstrap_db.log)
    rm -f /tmp/.bootstrap_db.log
    [ $rc -eq 0 ] || exit $rc
    export BUSINESS_ID
}

# ===== the steps =====
check_wildcard() { ./check_wildcard.sh "$TARGET_FILE"; }
scan() {
    # scan.sh depends on the DB/BUSINESS_ID/RESOLVERS/WORDLIST/HASH env
    export DB BUSINESS_ID RESOLVERS WORDLIST WORDLIST_HASH
    # the brute stage control
    [ -n "$SKIP_BRUTE" ]   && export SKIP_BRUTE=1
    [ -n "$FORCE_BRUTE" ]  && export FORCE_BRUTE=1
    [ -n "$BRUTE_MODE" ]   && export BRUTE_MODE
    ./scan.sh
}
scanner()        { [ -n "$ENABLE_TCP" ] && ./scanner.sh -all ${SCANNER_PORTS:+-p "$SCANNER_PORTS"} || ./scanner.sh ${SCANNER_PORTS:+-p "$SCANNER_PORTS"}; }
import() {
    python3 import_scan_results.py \
        --business      "$BUSINESS" \
        --db            "$DB" \
        --scan-dir      "$SCAN_DIR" \
        --target-file   "$TARGET_FILE" \
        --exclude-file  "$EXCLUDE_FILE" \
        --wildcard-file "$WILDCARD_OUT" \
        ${DRY_RUN_IMPORT:+--dry-run}
}

# the wrap up: the scope is upserted once more explicitly, so that the scope is in
# the DB before the input files are deleted
# (the import stage already did it once, this is the final commit, it is idempotent;
# it only touches the scopes table, not web/tcp)
finalize_scope() {
    python3 - "$DB" "$BUSINESS" "$TARGET_FILE" "$EXCLUDE_FILE" "$WILDCARD_OUT" <<'PY'
import sys, sqlite3
from datetime import datetime, timezone
from pathlib import Path
db, biz, tf, ef, wf = sys.argv[1:6]

def clean(line):
    line = line.strip().lstrip("﻿")
    if not line or line.startswith("#"): return None
    return line.split()[0].strip().lower().rstrip(".")

def read(p):
    if not Path(p).exists(): return []
    out, seen = [], set()
    for ln in Path(p).read_text(encoding="utf-8", errors="replace").splitlines():
        v = clean(ln)
        if v and v not in seen: out.append(v); seen.add(v)
    return out

targets  = read(tf)
excludes = read(ef)
wildcards = read(wf) if Path(wf).exists() else []
wset = set(wildcards)

now = datetime.now(timezone.utc).astimezone().isoformat(timespec="seconds")
conn = sqlite3.connect(db)
conn.execute("PRAGMA foreign_keys = ON")
row = conn.execute("SELECT id FROM businesses WHERE business_name=?", (biz,)).fetchone()
if not row:
    conn.execute("INSERT INTO businesses (business_name) VALUES (?)", (biz,))
    row = conn.execute("SELECT id FROM businesses WHERE business_name=?", (biz,)).fetchone()
bid = int(row[0])

def upsert(scope, asset, w):
    conn.execute(
        "INSERT INTO scopes (business_id, scope_name, asset, is_wildcard, created_at, updated_at, fetched_at) "
        "VALUES (?,?,?,?,?,?,?) "
        "ON CONFLICT(business_id, scope_name, asset) DO UPDATE SET "
        "  updated_at=excluded.updated_at, fetched_at=excluded.fetched_at, is_wildcard=excluded.is_wildcard",
        (bid, scope, asset, 1 if asset in wset else 0, now, now, now),
    )

for a in targets:  upsert("可测资产", a, wset)
for a in excludes: upsert("非可测资产", a, wset)
conn.commit()
conn.close()
print(f"[finalize_scope] {biz}: targets={len(targets)} excludes={len(excludes)} wildcards={len(wildcards)} (committed)")
PY
}

# -----------------------------------------------------------------------
# reverify (the 2026-10-03 relocation refactor)
#
# The old position: stage 3.6 of scanner.sh (lines 380-489), it ran inside the
# scanner.
#   The defect: the scanner stage was still writing new data, so is_active=0 in the
#   DB held both "the ones that went inactive yesterday"
#   and "the ones that really went inactive after today's scan", and the reverify
#   read a mixed state, which is semantically wrong.
#
# The new position: after the import is done, before finalize_scope.
#   At that point is_active=0 in the DB = the assets that really went inactive
#   after today's scan (the "clear the whole stage + reactivate" of the import
#   already handled most of the missed activations), and the reverify only covers
#   the few remaining missed activations. The semantics are clear and they line up
#   with the cron daily report.
#
# The flow:
#   1) read the inactive candidates of this business from the DB
#      (is_active=0 AND last_seen>=7d AND ips!='[]')
#      using the web_subdomains.ips field (the 2026-10-03 schema evolution, it is
#      written from the httpx JSONL)
#   2) write targets.lst (subdomain:port, one per line), with the reverse index
#      target->sid
#   3) one httpx -l batch feed (it lines up with the stage 3.5 CDN+LB parameters,
#      -rate-limit 50 -timeout 5)
#   4) a streaming JSONL parse -> a hit (200-299 + cl>1000 + not a WAF + not failed)
#      -> UPDATE is_active=1
#   5) a failure is isolated by try/except, it is not fatal; reverify_hits.tsv is
#      written for the manual audit
#
# The failure modes: no candidate in the DB / httpx does not exist / every httpx
# probe fails -> it exits 0 silently
# -----------------------------------------------------------------------
reverify() {
    python3 - "$DB" "$BUSINESS" "$SCAN_DIR" <<'PYREVERIFY'
import json, os, sqlite3, subprocess, sys
from collections import defaultdict
from datetime import datetime, timezone, timedelta
from pathlib import Path

# The i18n lookup lives in modules/main/lib, which is not on sys.path at
# this depth. Walk up to the repo root (the directory that holds
# "modules") and add the lib directory to the path.
for _p in Path.cwd().resolve().parents:
    if (_p / "modules").is_dir():
        sys.path.insert(0, str(_p / "modules" / "main" / "lib"))
        break
from i18n import t as _t

db_path, biz, scan_dir = sys.argv[1], sys.argv[2], sys.argv[3]

# 2026-10-03: the httpx path (env > the default).
HTTPX_BIN = os.environ.get("HTTPX_BIN") or str(Path.home() / ".pdtm/go/bin/httpx")
if not Path(HTTPX_BIN).exists():
    print(_t("main.pipeline.reverify_skipped_no_httpx", {"bin": HTTPX_BIN}), file=sys.stderr)
    sys.exit(0)

# read the candidates: the inactive ones (is_active=0).
# By spec (the user, 2026-10-04), the only necessary and sufficient condition for
# the deactivation is is_active=0, it has nothing to do with last_seen.
conn = sqlite3.connect(db_path)
conn.row_factory = sqlite3.Row
try:
    rows = conn.execute("""
        SELECT ws.id, ws.subdomain, ws.port, ws.ips,
               wh.business_id, b.business_name
          FROM web_subdomains ws
          JOIN web_hashes wh ON wh.id = ws.hash_id
          JOIN businesses b  ON b.id = wh.business_id
         WHERE ws.is_active = 0
         ORDER BY ws.id
    """).fetchall()
except sqlite3.OperationalError as exc:
    print(_t("main.pipeline.reverify_db_read_failed", {"error": exc}), file=sys.stderr)
    sys.exit(0)

if not rows:
    print(_t("main.pipeline.reverify_no_candidates", {"biz": biz}))
    sys.exit(0)

print(_t("main.pipeline.reverify_candidates", {"biz": biz, "count": len(rows)}))

scan_dir_p = Path(scan_dir)
scan_dir_p.mkdir(parents=True, exist_ok=True)
hits_path = scan_dir_p / "reverify_hits.tsv"

WAF_KW = ("waf", "firewall", "web应用防火墙", "blocked", "denied")

def is_hit(j: dict) -> bool:
    sc = j.get("status_code") or 0
    cl = j.get("content_length") or 0
    title_l = (j.get("title") or "").lower()
    is_waf = any(k in title_l for k in WAF_KW)
    return (200 <= sc < 300) and cl > 1000 and not is_waf and not j.get("failed")

def run_httpx(input_path: Path, host_header: str | None) -> list[dict]:
    args = [str(HTTPX_BIN),
            "-sc", "-cl", "-title", "-random-agent",
            "-follow-redirects", "-max-redirects", "3",
            "-rate-limit", "50", "-timeout", "5",
            "-silent", "-no-color", "-json"]
    if host_header:
        args += ["-H", f"Host: {host_header}"]
    args += ["-l", str(input_path)]
    try:
        proc = subprocess.run(args, stdin=subprocess.DEVNULL,
                              capture_output=True, text=True, timeout=600)
    except subprocess.TimeoutExpired as exc:
        print(f"[reverify][warn] httpx timeout after 600s on {input_path.name}", file=sys.stderr)
        return []
    except Exception as exc:
        print(_t("main.pipeline.reverify_httpx_start_failed", {"error": exc}), file=sys.stderr)
        return []
    out = []
    for line in proc.stdout.splitlines():
        line = line.strip()
        if not line:
            continue
        try:
            out.append(json.loads(line))
        except json.JSONDecodeError:
            continue
    return out

